#define NGLYPH_SRC ((int)(sizeof(glyph_src) / sizeof(glyph_src[0])))

static const char *glyph_lookup(int c)
{
  int i;
  for (i = 0; i < NGLYPH_SRC; i++)
    if (glyph_src[i].c == c) return glyph_src[i].art;
  return 0;
}

/* dst is RGBA, w/h are the texture dimensions (128x64: 16 x 6 glyph cells).
 * The strip has to be a power-of-two texture: the GS silently mis-samples
 * anything else and the HUD comes out as garbage on real hardware. */
void font_build(unsigned char *dst, int w, int h)
{
  int g, x, y, row, col;

  memset(dst, 0, (size_t)w * h * 4);
  if (w < FONT_TEX_W || h < FONT_TEX_H) return;

  for (g = 0; g < NGLYPH; g++) {
    const char *art = glyph_lookup(FIRST_CHAR + g);
    int gx = (g % FONT_COLS) * FONT_CELL_W;
    int gy = (g / FONT_COLS) * FONT_CELL_H;
    if (!art) continue;
    for (row = 0; row < 7; row++) {
      for (col = 0; col < 5; col++) {
        if (art[row * 5 + col] != '#') continue;
        x = gx + col;
        y = gy + row;
        dst[(y * w + x) * 4 + 0] = 255;
        dst[(y * w + x) * 4 + 1] = 255;
        dst[(y * w + x) * 4 + 2] = 255;
        dst[(y * w + x) * 4 + 3] = 255;
      }
    }
  }
}

float text_width(const char *s, float scale)
{
  int n = 0;
  while (s && *s) {
    unsigned char c = (unsigned char)*s;
    if (c >= 'a' && c <= 'z') c = (unsigned char)(c - 'a' + 'A');
    if (c >= FIRST_CHAR && c <= LAST_CHAR) n++;
    s++;
  }
  return (float)n * GLYPH_W * scale;
}
